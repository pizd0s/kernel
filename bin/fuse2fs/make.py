#!/usr/bin/env python3
"""Build fuse2fs for the system: e2fsprogs' FUSE server of ext2, ext3 and
ext4 file systems, from its release tarball, never edited, on the system's
libfuse (lib/fuse). What e2fsprogs' configure would make is made here: its
config.h is ours (config.h), the type headers come from their templates
with wasm32's sizes, the error table from compile_et's awk scripts, and the
CRC32C tables as its gen_crc32ctable prints them. clang compiles
libext2fs, libcom_err, libuuid, fuse2fs and the journal code it takes from
debugfs and e2fsck, with libfuse and the protocol's sources, for wasm32
against lib/c's headers, and wasm-ld links them with libc.a.

    make.py <clang> <wasm-ld> <libc-include> <libc.a> <e2fsprogs.tar.xz> <fuse2fs.wasm>
"""
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "dev"))

import wasm  # noqa: E402

VERSION = "1.47.4"

CFLAGS = ["-O2", "-std=gnu11", "-w", "-DHAVE_CONFIG_H"]
CXXFLAGS = ["-O2", "-std=c++23", "-fno-exceptions", "-fno-rtti", "-nostdinc++", "-Wall", "-Wextra", "-Werror"]

LINK = ["--stack-first", "--max-memory=4294967296", "--export=__heap_base",
        "--export=__stack_pointer", "--gc-sections"]

EXT2FS = """
    alloc alloc_sb alloc_stats alloc_tables atexit badblocks bb_inode bitmaps bitops blkmap64_ba
    blkmap64_rb blknum block bmap check_desc closefs crc16 crc32c csum dblist dblist_dir dirblock
    dirhash dir_iterate expanddir ext_attr extent fallocate fileio finddev flushb freefs gen_bitmap
    gen_bitmap64 get_num_dirs get_pathname getenv getsize getsectsize hashmap i_block icount ind_block
    initialize inline inline_data inode io_manager ismounted link llseek lookup mkdir mkjournal mmp
    namei native newdir nls_utf8 openfs orphan progress punch qcow2 rbtree read_bb read_bb_file
    res_gdt rw_bitmaps sha512 swapfs symlink unix_io unlink valid_blk version
""".split()
COM_ERR = ["error_message", "et_name", "init_et", "com_err", "com_right"]
UUID = ["clear", "compare", "copy", "gen_uuid", "isnull", "pack", "parse", "unpack", "unparse", "uuid_time"]
FUSE2FS = ["misc/fuse2fs.c", "debugfs/journal.c", "e2fsck/recovery.c", "e2fsck/revoke.c"]

SIZES = {"@SIZEOF_INT@": "4", "@SIZEOF_LONG@": "4", "@SIZEOF_LONG_LONG@": "8", "@SIZEOF_SHORT@": "2",
         "@ASM_TYPES_HEADER@": "", "@PUBLIC_CONFIG_HEADER@": "", "@E2FSPROGS_VERSION@": VERSION}


def substituted(template, output):
    text = template.read_text()
    for key, value in SIZES.items():
        text = text.replace(key, value)
    output.write_text(text)


def crc32c_tables():
    """lib/ext2fs/crc32c_table.h: gen_crc32ctable's tables of 64-bit CRCs, 8 rows."""
    rows = 8
    be = [[0] * 256 for _ in range(rows)]
    crc = 0x80000000
    i = 1
    while i < 256:
        crc = ((crc << 1) ^ (0x04C11DB7 if crc & 0x80000000 else 0)) & 0xFFFFFFFF
        for j in range(i):
            be[0][i + j] = crc ^ be[0][j]
        i <<= 1
    for i in range(256):
        crc = be[0][i]
        for j in range(1, rows):
            crc = (be[0][(crc >> 24) & 0xFF] ^ (crc << 8)) & 0xFFFFFFFF
            be[j][i] = crc
    le = [[0] * 256 for _ in range(rows)]
    crc = 1
    i = 128
    while i:
        crc = (crc >> 1) ^ (0x82F63B78 if crc & 1 else 0)
        for j in range(0, 256, 2 * i):
            le[0][i + j] = crc ^ le[0][j]
        i >>= 1
    for i in range(256):
        crc = le[0][i]
        for j in range(1, rows):
            crc = le[0][crc & 0xFF] ^ (crc >> 8)
            le[j][i] = crc

    def table(name, values, trans):
        body = ",\n".join("{" + ", ".join(f"{trans}(0x{v:08x}L)" for v in row) + "}" for row in values)
        return f"static const uint32_t {name}[{rows}][256] = {{\n{body}}};\n"

    return "/* generated by bin/fuse2fs/make.py, as gen_crc32ctable prints it */\n\n" + table("crc32table_be", be, "tobe") + \
        table("crc32ctable_le", le, "tole")


def main():
    if len(sys.argv) != 7:
        raise SystemExit(__doc__)
    cc, ld, include, libc, tarball, output = sys.argv[1:7]
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(dir=output.parent, prefix="fuse2fs-") as work:
        work = Path(work)
        with tarfile.open(tarball) as archive:
            archive.extractall(work, filter="data")
        tree = work / f"e2fsprogs-{VERSION}"
        lib = tree / "lib"
        shutil.copy(HERE / "config.h", lib / "config.h")
        (lib / "dirpaths.h").write_text('#define LOCALEDIR "/usr/share/locale"\n#define ROOT_SYSCONFDIR "/etc"\n')
        substituted(lib / "ext2fs/ext2_types.h.in", lib / "ext2fs/ext2_types.h")
        substituted(lib / "uuid/uuid_types.h.in", lib / "uuid/uuid_types.h")
        substituted(lib / "uuid/uuid.h.in", lib / "uuid/uuid.h")
        substituted(lib / "blkid/blkid_types.h.in", lib / "blkid/blkid_types.h")
        substituted(lib / "blkid/blkid.h.in", lib / "blkid/blkid.h")
        substituted(lib / "ext2fs/ext2_err.et.in", lib / "ext2fs/ext2_err.et")
        for directory, table in (("ext2fs", "ext2_err"), ("support", "prof_err")):
            for awk, suffix in (("et_h.awk", "h"), ("et_c.awk", "c")):
                subprocess.run(["awk", "-f", str(lib / "et" / awk), f"outfile={table}.{suffix}", f"outfn={table}.{suffix}", f"{table}.et"],
                               cwd=lib / directory, check=True)
        (lib / "ext2fs/crc32c_table.h").write_text(crc32c_tables())

        system = ["-isystem", str(Path(include).resolve())]
        c = [*CFLAGS, "-I", str(lib), "-I", str(lib / "ext2fs"), "-I", str(tree / "e2fsck"), "-I", str(ROOT / "lib/fuse"), *system]
        sources = [lib / "ext2fs" / f"{n}.c" for n in [*EXT2FS, "ext2_err"]]
        sources += [lib / "et" / f"{n}.c" for n in COM_ERR]
        sources += [lib / "uuid" / f"{n}.c" for n in UUID]
        sources += [lib / "e2p/parse_num.c", HERE / "blkid.c"]
        units = [(s, work / "o" / f"{i}-{s.stem}.o", c) for i, s in enumerate(sources)]
        # The journal code is debugfs's, built for fuse2fs as misc builds it.
        journal = [*c, "-I", str(tree / "misc"), "-I", str(tree / "debugfs"), "-DDEBUGFS"]
        units += [(tree / n, work / "o" / f"j{i}-{Path(n).stem}.o", journal) for i, n in enumerate(FUSE2FS)]
        cxx = [*CXXFLAGS, "-I", str(ROOT), *system]
        ours = sorted((ROOT / "lib/fuse").glob("*.cpp")) + sorted((ROOT / "lib/protocol").glob("*.cpp"))
        units += [(s, work / "o" / f"x{i}-{s.stem}.o", cxx) for i, s in enumerate(ours)]
        wasm.compile_all(cc, units, places=[work])
        subprocess.run([ld, *LINK, "-o", str(output), *(str(o) for _, o, _ in units), libc], check=True)


if __name__ == "__main__":
    main()
