type Errno uint32

func (e Errno) Error() string {
	return e.error()
}

func (e Errno) error() string {
	if s, ok := errnoMessages[e]; ok {
		return s
	}

	return fmt.Sprintf("errno %d", int(e))
}

func hostErrno(err error) Errno {
	var e syscall.Errno

	if errors.As(err, &e) {
		if own, ok := hostErrnos[e]; ok {
			return own
		}
	}

	return EIO
}
